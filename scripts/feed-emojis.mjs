// Generate the CI status emoji used by the GitHub updates feed.
//
//   npm run feed-emojis   -> writes assets/discord-feed-emojis/* and src/github/feed-emoji-assets.ts
//
// The Worker uploads these as Discord application emoji on first use.

import { mkdir, writeFile } from "node:fs/promises";
import sharp from "sharp";

const SIZE = 128;
const GREEN = "#3fb950";
const RED = "#f85149";
const AMBER = "#d29922";
const GREY = "#8b949e";
const WHITE = `fill="none" stroke="#fff" stroke-width="13" stroke-linecap="round" stroke-linejoin="round"`;

const svg = (body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 128 128">${body}</svg>`;

const STATIC = {
  gh_success: svg(
    `<circle cx="64" cy="64" r="58" fill="${GREEN}"/><path d="m38 66 17 17 35-37" ${WHITE}/>`,
  ),
  gh_failure: svg(
    `<circle cx="64" cy="64" r="58" fill="${RED}"/><path d="m44 44 40 40M84 44 44 84" ${WHITE}/>`,
  ),
  gh_skipped: svg(
    `<circle cx="64" cy="64" r="50" fill="none" stroke="${GREY}" stroke-width="13"/><path d="m31 97 66-66" fill="none" stroke="${GREY}" stroke-width="13" stroke-linecap="round"/>`,
  ),
  gh_queued: svg(
    `<circle cx="64" cy="64" r="50" fill="none" stroke="${AMBER}" stroke-width="13" stroke-dasharray="20 19.27" stroke-linecap="round"/>`,
  ),
};

// GitHub's in-progress mark: a ring around a dot, with a bright arc sweeping it.
// GIF alpha is binary, so the track is an opaque darker amber.
const FRAMES = 20;
const runningFrame = (index) =>
  svg(
    `<circle cx="64" cy="64" r="50" fill="none" stroke="#6b5420" stroke-width="13"/>` +
      `<circle cx="64" cy="64" r="50" fill="none" stroke="${AMBER}" stroke-width="13" stroke-linecap="round" stroke-dasharray="85 400" transform="rotate(${(index * 360) / FRAMES - 90} 64 64)"/>` +
      `<circle cx="64" cy="64" r="21" fill="${AMBER}"/>`,
  );

const outputs = {};
await mkdir("assets/discord-feed-emojis", { recursive: true });
for (const [name, source] of Object.entries(STATIC)) {
  const png = await sharp(Buffer.from(source)).png().toBuffer();
  await writeFile(`assets/discord-feed-emojis/${name}.png`, png);
  outputs[name] = `data:image/png;base64,${png.toString("base64")}`;
}
const frames = await Promise.all(
  Array.from({ length: FRAMES }, (_, index) =>
    sharp(Buffer.from(runningFrame(index)))
      .png()
      .toBuffer(),
  ),
);
const gif = await sharp(frames, { join: { animated: true } })
  .gif({ delay: Array(FRAMES).fill(50), loop: 0, effort: 10 })
  .toBuffer();
await writeFile("assets/discord-feed-emojis/gh_running.gif", gif);
outputs.gh_running = `data:image/gif;base64,${gif.toString("base64")}`;

await writeFile(
  "src/github/feed-emoji-assets.ts",
  `// Generated by scripts/feed-emojis.mjs. Do not edit.\n\nexport const FEED_EMOJI_IMAGES = ${JSON.stringify(outputs, null, 2)} as const;\n`,
);
console.log(Object.fromEntries(Object.entries(outputs).map(([k, v]) => [k, v.length])));
